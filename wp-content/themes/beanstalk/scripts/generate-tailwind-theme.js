#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const themeRoot = path.resolve(__dirname, '..');
const themeJsonPath = path.join(themeRoot, 'theme.json');
const outputPath = path.join(themeRoot, 'assets/css/theme-tokens.css');
const watchMode = process.argv.includes('--watch');

function readThemeJson() {
  try {
    return JSON.parse(fs.readFileSync(themeJsonPath, 'utf8'));
  } catch (error) {
    throw new Error(`Unable to read ${themeJsonPath}: ${error.message}`);
  }
}

function asArray(value) {
  return Array.isArray(value) ? value : [];
}

function assertSlug(slug, tokenType) {
  if (typeof slug !== 'string' || !/^[a-z0-9][a-z0-9-]*$/i.test(slug)) {
    throw new Error(`Invalid ${tokenType} slug: ${JSON.stringify(slug)}`);
  }

  return slug;
}

function assertCssValue(value, tokenName) {
  if (typeof value !== 'string' || value.trim() === '' || /[;{}\r\n]/.test(value)) {
    throw new Error(`Invalid CSS value for ${tokenName}: ${JSON.stringify(value)}`);
  }

  return value.trim();
}

function addToken(lines, namespace, slug, value, tokenType) {
  const safeSlug = assertSlug(slug, tokenType);
  const property = `--${namespace}-${safeSlug}`;
  lines.push(`  ${property}: ${assertCssValue(value, property)};`);
}

function generateThemeTokens(themeJson) {
  const settings = themeJson.settings || {};
  const lines = [
    '/*',
    ' * AUTO-GENERATED from theme.json by scripts/generate-tailwind-theme.js.',
    ' * Do not edit this file directly; run npm run generate:tokens.',
    ' */',
    '@theme {',
  ];

  for (const color of asArray(settings.color?.palette)) {
    addToken(lines, 'color', color.slug, `var(--wp--preset--color--${color.slug})`, 'color');
  }

  for (const font of asArray(settings.typography?.fontFamilies)) {
    addToken(lines, 'font', font.slug, `var(--wp--preset--font-family--${font.slug})`, 'font family');
  }

  for (const fontSize of asArray(settings.typography?.fontSizes)) {
    addToken(lines, 'text', fontSize.slug, `var(--wp--preset--font-size--${fontSize.slug})`, 'font size');
  }

  for (const slug of Object.keys(settings.custom?.lineHeight || {})) {
    addToken(lines, 'leading', slug, `var(--wp--custom--line-height--${slug})`, 'line height');
  }

  for (const spacing of asArray(settings.spacing?.spacingSizes)) {
    addToken(lines, 'spacing', spacing.slug, `var(--wp--preset--spacing--${spacing.slug})`, 'spacing');
  }
  lines.push('}', '');
  return lines.join('\n');
}

function writeThemeTokens() {
  const css = generateThemeTokens(readThemeJson());
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, css, 'utf8');
  console.log(`Generated ${path.relative(themeRoot, outputPath)} from theme.json`);
}

writeThemeTokens();

if (watchMode) {
  let debounceTimer;
  const handleThemeChange = (current, previous) => {
    if (current.mtimeMs === previous.mtimeMs && current.size === previous.size) {
      return;
    }

    clearTimeout(debounceTimer);
    debounceTimer = setTimeout(() => {
      try {
        writeThemeTokens();
      } catch (error) {
        console.error(error.message);
      }
    }, 100);
  };

  fs.watchFile(themeJsonPath, { interval: 250, persistent: true }, handleThemeChange);

  const stopWatching = () => {
    clearTimeout(debounceTimer);
    fs.unwatchFile(themeJsonPath, handleThemeChange);
    process.exit(0);
  };

  process.once('SIGINT', stopWatching);
  process.once('SIGTERM', stopWatching);
  console.log(`Watching ${path.relative(themeRoot, themeJsonPath)} for changes...`);
}
